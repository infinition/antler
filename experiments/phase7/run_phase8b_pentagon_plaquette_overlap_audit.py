"""Joint overlap audit for a mixed pentagon and an adjacent mixed plaquette.

This is the first local compatibility gate beyond an isolated odd-weight twist
endpoint word.  The pentagon XZXZX and a neighboring ZXZX plaquette share two
links with opposite Pauli labels, so their target stabilizers commute.  Both
are generated by explicit neutral walkers and jointly downfolded.
"""
from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
from scipy import sparse
from scipy.sparse import linalg as sparse_linalg


ROOT = Path(__file__).resolve().parents[2]

DETUNING = 10.0
RATIOS = (0.20, 0.15, 0.10, 0.075, 0.05, 0.0375, 0.025)
EDGES = 7
GAUGE_DIMENSION = 1 << EDGES
PENTAGON_PATTERN = (1, 3, 1, 3, 1)
PENTAGON_EDGES = (0, 1, 2, 3, 4)
PLAQUETTE_PATTERN = (3, 1, 3, 1)
PLAQUETTE_EDGES = (0, 1, 5, 6)
PENTAGON_STATES = 5
PLAQUETTE_STATES = 4
DIMENSION = GAUGE_DIMENSION * PENTAGON_STATES * PLAQUETTE_STATES
PAULI_NAMES = "IXYZ"
PENTAGON_LABEL = "XZXZXII"
PLAQUETTE_LABEL = "ZXIIIZX"
PRODUCT_LABEL = "YYXZXZX"


def index(gauge: int, pentagon_walker: int, plaquette_walker: int) -> int:
    return ((pentagon_walker * PLAQUETTE_STATES + plaquette_walker) * GAUGE_DIMENSION) + gauge


def z_eigenvalue(gauge: int, edge: int) -> float:
    return -1.0 if (gauge >> edge) & 1 else 1.0


def add_symmetric(matrix: sparse.lil_matrix, row: int, column: int, value: complex) -> None:
    matrix[row, column] += value
    matrix[column, row] += np.conj(value)


def add_walker_transitions(
    matrix: sparse.lil_matrix,
    gauge: int,
    pentagon_walker: int,
    plaquette_walker: int,
    coupling: float,
    *,
    which: str,
) -> None:
    if which == "pentagon":
        states, edges, pattern = PENTAGON_STATES, PENTAGON_EDGES, PENTAGON_PATTERN
        walker = pentagon_walker
    else:
        states, edges, pattern = PLAQUETTE_STATES, PLAQUETTE_EDGES, PLAQUETTE_PATTERN
        walker = plaquette_walker
    for first in range(states):
        if walker != first:
            continue
        second = (first + 1) % states
        edge, pauli = edges[first], pattern[first]
        new_gauge = gauge ^ (1 << edge) if pauli == 1 else gauge
        amplitude = coupling if pauli == 1 else coupling * z_eigenvalue(gauge, edge)
        if which == "pentagon":
            row = index(new_gauge, second, plaquette_walker)
        else:
            row = index(new_gauge, pentagon_walker, second)
        column = index(gauge, pentagon_walker, plaquette_walker)
        add_symmetric(matrix, row, column, amplitude)


def build_hamiltonian(coupling: float) -> sparse.csr_matrix:
    hamiltonian = sparse.lil_matrix((DIMENSION, DIMENSION), dtype=complex)
    for gauge in range(GAUGE_DIMENSION):
        for pentagon_walker in range(PENTAGON_STATES):
            for plaquette_walker in range(PLAQUETTE_STATES):
                column = index(gauge, pentagon_walker, plaquette_walker)
                if pentagon_walker:
                    hamiltonian[column, column] += DETUNING
                if plaquette_walker:
                    hamiltonian[column, column] += DETUNING
                add_walker_transitions(
                    hamiltonian, gauge, pentagon_walker, plaquette_walker, coupling, which="pentagon"
                )
                add_walker_transitions(
                    hamiltonian, gauge, pentagon_walker, plaquette_walker, coupling, which="plaquette"
                )
    return hamiltonian.tocsr()


def pauli_action(codes: tuple[int, ...], state: int) -> tuple[int, complex]:
    target = state
    phase = 1.0 + 0.0j
    for edge, code in enumerate(codes):
        bit = (state >> edge) & 1
        if code == 1:
            target ^= 1 << edge
        elif code == 2:
            target ^= 1 << edge
            phase *= 1j if bit == 0 else -1j
        elif code == 3:
            phase *= -1.0 if bit else 1.0
    return target, phase


def pauli_coefficients(hamiltonian: np.ndarray) -> dict[str, complex]:
    coefficients: dict[str, complex] = {}
    for codes in itertools.product(range(4), repeat=EDGES):
        value = 0.0j
        for column in range(GAUGE_DIMENSION):
            row, phase = pauli_action(codes, column)
            value += np.conj(phase) * hamiltonian[row, column]
        coefficients["".join(PAULI_NAMES[code] for code in codes)] = value / GAUGE_DIMENSION
    return coefficients


def pauli_matrix(codes: tuple[int, ...]) -> np.ndarray:
    matrix = np.zeros((GAUGE_DIMENSION, GAUGE_DIMENSION), dtype=complex)
    for column in range(GAUGE_DIMENSION):
        row, phase = pauli_action(codes, column)
        matrix[row, column] = phase
    return matrix


def downfold_at_zero(hamiltonian: sparse.csr_matrix) -> tuple[np.ndarray, float]:
    low = np.asarray([index(gauge, 0, 0) for gauge in range(GAUGE_DIMENSION)], dtype=int)
    mask = np.ones(DIMENSION, dtype=bool)
    mask[low] = False
    high = np.flatnonzero(mask)
    h_lh = hamiltonian[low][:, high]
    h_hh = hamiltonian[high][:, high].tocsc()
    h_hl = hamiltonian[high][:, low].toarray()
    effective = -np.asarray(h_lh @ sparse_linalg.spsolve(h_hh, h_hl))
    return effective, float(np.linalg.norm(effective - effective.conj().T, ord="fro"))


def main() -> None:
    pentagon = pauli_matrix((1, 3, 1, 3, 1, 0, 0))
    plaquette = pauli_matrix((3, 1, 0, 0, 0, 3, 1))
    rows = []
    for ratio in RATIOS:
        effective, hermiticity = downfold_at_zero(build_hamiltonian(ratio * DETUNING))
        coefficients = pauli_coefficients(effective)
        allowed = {"IIIIIII", PENTAGON_LABEL, PLAQUETTE_LABEL, PRODUCT_LABEL}
        unwanted = {label: value for label, value in coefficients.items() if label not in allowed}
        label, value = max(unwanted.items(), key=lambda item: abs(item[1]))
        rows.append({
            "coupling_over_detuning": ratio,
            "pentagon_coefficient": float(np.real_if_close(coefficients[PENTAGON_LABEL])),
            "plaquette_coefficient": float(np.real_if_close(coefficients[PLAQUETTE_LABEL])),
            "commuting_product_coefficient": float(np.real_if_close(coefficients[PRODUCT_LABEL])),
            "maximum_outside_generated_algebra_coefficient": float(abs(value)),
            "largest_outside_generated_algebra_pauli": label,
            "zero_energy_schur_hermiticity_residual": hermiticity,
            "target_commutator_frobenius": float(np.linalg.norm(pentagon @ plaquette - plaquette @ pentagon, ord="fro")),
        })
    deep = [row for row in rows if row["coupling_over_detuning"] <= 0.075]
    powers = {
        name: float(np.polyfit(
            np.log([row["coupling_over_detuning"] for row in deep]),
            np.log(np.abs([row[name] for row in deep])),
            1,
        )[0])
        for name in ("pentagon_coefficient", "plaquette_coefficient", "commuting_product_coefficient")
    }
    output = {
        "schema": "antler.phase8b.pentagon-plaquette-overlap-audit.v1",
        "parameters": {
            "gauge_links": EDGES,
            "detuning": DETUNING,
            "ratios": list(RATIOS),
            "pentagon": PENTAGON_LABEL,
            "plaquette": PLAQUETTE_LABEL,
            "shared_links": [0, 1],
            "new_primitives": "one neutral five-state and one neutral four-state phase-controlled X/Z-conditioned walker",
            "downfolding": "exact zero-energy Schur complement onto both walkers low",
        },
        "dimensions": {"total": DIMENSION, "low_gauge_subspace": GAUGE_DIMENSION, "high_walker_subspace": DIMENSION - GAUGE_DIMENSION},
        "rows": rows,
        "deep_sw_powers": powers,
        "decision": (
            "The explicit mixed pentagon and adjacent plaquette walkers jointly close on their commuting local algebra. "
            "No Pauli word outside {I,pentagon,plaquette,product} is resolved in the overlap block."
        ),
        "claim_boundary": (
            "This is a one-overlap compatibility audit, not a complete dislocated surface-code geometry. It does not establish "
            "a branch cut, twist endpoints, a fusion space, defect motion, a braid or a native ANTLER realization."
        ),
    }
    result = ROOT / "results" / "phase7" / "phase8b_pentagon_plaquette_overlap_audit.json"
    result.write_text(json.dumps(output, indent=2), encoding="utf-8")
    print(json.dumps(output, indent=2))


if __name__ == "__main__":
    main()
