"""Conservative finite-duration implementation test for the Phase 7D echo kicks.

The ideal Q echo is replaced by onsite-potential kicks exp(-i pi K), with
K=sum_j j(n_aj+n_bj)+N_mediator.  During each kick the active pulse
Hamiltonian is deliberately left on, so the result bounds the simple
"strong potential but no perfect switch-off" implementation.
"""
from __future__ import annotations

import json
from pathlib import Path
import sys

import numpy as np
from scipy.sparse import diags


ROOT = Path(__file__).resolve().parents[2]
PHASE7 = ROOT / "experiments" / "phase7"
if str(PHASE7) not in sys.path:
    sys.path.insert(0, str(PHASE7))

from run_phase7d_four_rung_microscopic_pulse_audit import (
    FRAME, L, LINKS, LOGICAL_PA, LOGICAL_PB, LOW_MODES, PULSE_TIME, STATES,
    evolve, leakage, pair_gate, projected, pulse_hamiltonian, rail_rotation,
    remove_global_phase,
)


LEG_HOPPING, EPSILON, SUBCYCLES = 1.0, 1e-2, 16
KAPPAS = (100.0, 200.0, 400.0, 800.0)


def k_values() -> np.ndarray:
    output = []
    for raw_state in STATES:
        state = int(raw_state)
        rail = sum(
            rung * (((state >> (2 * rung)) & 1) + ((state >> (2 * rung + 1)) & 1))
            for rung in range(L)
        )
        output.append(rail + (state >> LOW_MODES).bit_count())
    return np.asarray(output, dtype=float)


K_VALUES = k_values()


def finite_kick_pulse(vectors: np.ndarray, active_links: tuple[int, ...], kind_prefix: str,
                      kappa: float) -> np.ndarray:
    h_plus = pulse_hamiltonian(active_links, kind_prefix, EPSILON, LEG_HOPPING)
    kick_hamiltonian = h_plus + diags(kappa * K_VALUES, format="csr")
    delta, kick_time = PULSE_TIME / SUBCYCLES, np.pi / kappa
    for _ in range(SUBCYCLES):
        vectors = evolve(vectors, h_plus, delta / 4.0)
        vectors = evolve(vectors, kick_hamiltonian, kick_time)
        vectors = evolve(vectors, h_plus, delta / 2.0)
        vectors = evolve(vectors, kick_hamiltonian, kick_time)
        vectors = evolve(vectors, h_plus, delta / 4.0)
    return vectors


def finite_kick_pair_gate(vectors: np.ndarray, active_links: tuple[int, ...], kappa: float) -> np.ndarray:
    rungs = tuple(sorted({rung for link in active_links for rung in LINKS[link]}))
    ry, rx = rail_rotation("y", rungs), rail_rotation("x", rungs)
    vectors = evolve(vectors, ry, np.pi / 4.0)
    vectors = finite_kick_pulse(vectors, active_links, "same", kappa)
    vectors = evolve(vectors, ry, -np.pi / 4.0)
    vectors = evolve(vectors, rx, np.pi / 4.0)
    vectors = finite_kick_pulse(vectors, active_links, "opposite", kappa)
    return evolve(vectors, rx, -np.pi / 4.0)


def metrics(vectors: np.ndarray, reference: np.ndarray) -> dict:
    logical = projected(vectors)
    return {
        "monomer_leakage": leakage(vectors),
        "logical_deviation_from_zero_leg_schedule": float(np.linalg.norm(
            logical - remove_global_phase(reference, logical), ord=2
        )),
        "logical_parity_a_residual": float(np.linalg.norm(logical @ LOGICAL_PA - LOGICAL_PA @ logical, ord=2)),
        "logical_parity_b_residual": float(np.linalg.norm(logical @ LOGICAL_PB - LOGICAL_PB @ logical, ord=2)),
        "logical_singular_value_min": float(np.linalg.svd(logical, compute_uv=False)[-1]),
    }


def main() -> None:
    reference = projected(pair_gate(pair_gate(FRAME.copy(), (0, 2), 0.0), (1,), 0.0))
    rows = []
    for kappa in KAPPAS:
        even = finite_kick_pair_gate(FRAME.copy(), (0, 2), kappa)
        complete = finite_kick_pair_gate(even, (1,), kappa)
        rows.append({
            "kick_rate_kappa": kappa,
            "max_rail_onsite_rate_3kappa": 3.0 * kappa,
            "kick_duration_pi_over_kappa": np.pi / kappa,
            "total_kick_time_per_mediator_pulse": 2.0 * SUBCYCLES * np.pi / kappa,
            **metrics(complete, reference),
        })
    out = {
        "schema": "antler.phase7d.finite-phase-kick-audit.v1",
        "implementation": (
            "Q is generated by an onsite potential K=sum_j j(n_aj+n_bj)+N_mediator. The active conversion and leg-hopping "
            "Hamiltonian remains on during the finite kick, making this a conservative non-instantaneous-kick test."
        ),
        "parameters": {
            "leg_hopping_during_pulses": LEG_HOPPING,
            "inactive_channel_coupling_over_g": EPSILON,
            "echo_subcycles": SUBCYCLES,
            "kick_rate_scan": list(KAPPAS),
        },
        "rows": rows,
        "decision": (
            "Finite onsite-potential phase-kick preflight only. It tests whether strong but non-instantaneous local potentials can "
            "approximate the ideal echo under a deliberately always-on pulse Hamiltonian."
        ),
        "claim_boundary": (
            "No available ANTLER hardware bandwidth, switchability, calibration error or decoherence has been derived. Passing this "
            "finite block does not demonstrate a protected phase, a 2D code, braiding, non-Abelian statistics, universality or fault tolerance."
        ),
    }
    path = ROOT / "results" / "phase7" / "finite_phase_kick_audit.json"
    path.write_text(json.dumps(out, indent=2), encoding="utf-8")
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
