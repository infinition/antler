"""Explicit flip-monomial projection of the crossed-quartet effective operator.

Question audited: does the crossed charge-two quartet
``d1(a0a1+b2b3), d2(b0b1+a2a3)`` generate the full four-body stabilizer
``XXXX`` on the monomer manifold, or only a strict subset of its sixteen flip
monomials?

Method: exact fixed-charge diagonalization and polar downfolding (the same
machinery as the cancellation audit), then a direct matrix-element projection
of the traceless effective Hamiltonian onto

1. the eight antipodal monomer pairs (states differing on all four edges) --
   the full ``XXXX`` has all eight equal, the all-flip has exactly one;
2. off-diagonal content grouped by Hamming (flip) distance 1..4;
3. the eight-Pauli-word family generated by the all-flip operator
   ``F = |aaaa><bbbb| + h.c. = (XXXX - sum of six XXYY-type words + YYYY)/8``
   whose squared ``XXXX`` share is exactly 1/8, an alignment ceiling that no
   diagonal counterterm can raise.

A GHZ-readability control on the idealized single-plaquette doublet is
included: a single-rung ``Z`` acts logically on the ``F`` cat pair.

This is a correction addendum control for Phase 7C. It promotes nothing.
"""
from __future__ import annotations

import json
from pathlib import Path
import sys

import numpy as np


ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from antler.phase7_microscopic_optimizer import (
    LOW_MANIFOLD_DIMENSION,
    MicroscopicCandidate2D,
    PairConversionChannel,
    evaluate_local_candidate,
    pauli_word,
    rail_mode,
)


U, DELTA = 20.0, 10.0
G_VALUES = (0.30, 0.50, 0.90, 1.30)
FLIP_FAMILY = ("XXXX", "XXYY", "XYXY", "XYYX", "YXXY", "YXYX", "YYXX", "YYYY")
# Expected relative signs inside F = (XXXX - six mixed words + YYYY)/8.
FLIP_FAMILY_SIGNS = {label: (-1.0 if label.count("Y") == 2 else 1.0) for label in FLIP_FAMILY}


def crossed_channels(g: float) -> tuple[PairConversionChannel, ...]:
    return (
        PairConversionChannel(
            "cross_aa01_bb23", DELTA, g, 0.0,
            ((rail_mode(0, 0), rail_mode(1, 0), 1.0), (rail_mode(2, 1), rail_mode(3, 1), 1.0)),
        ),
        PairConversionChannel(
            "cross_bb01_aa23", DELTA, g, 0.0,
            ((rail_mode(0, 1), rail_mode(1, 1), 1.0), (rail_mode(2, 0), rail_mode(3, 0), 1.0)),
        ),
    )


def effective_from_coefficients(coefficients: dict[str, float]) -> np.ndarray:
    matrix = np.zeros((LOW_MANIFOLD_DIMENSION, LOW_MANIFOLD_DIMENSION), dtype=complex)
    for label, value in coefficients.items():
        if label == "IIII":
            continue
        matrix += value * pauli_word(label)
    return matrix


def flip_distance_split(matrix: np.ndarray) -> dict[str, float]:
    split = {str(distance): 0.0 for distance in range(1, 5)}
    for row in range(LOW_MANIFOLD_DIMENSION):
        for column in range(LOW_MANIFOLD_DIMENSION):
            if row == column:
                continue
            split[str((row ^ column).bit_count())] += float(abs(matrix[row, column]) ** 2)
    return {key: float(np.sqrt(value)) for key, value in split.items()}


def antipodal_elements(matrix: np.ndarray) -> list[dict]:
    rows = []
    for state in range(LOW_MANIFOLD_DIMENSION // 2):
        antipode = state ^ (LOW_MANIFOLD_DIMENSION - 1)
        element = complex(matrix[antipode, state])
        rows.append({
            "monomer": format(state, "04b").replace("0", "a").replace("1", "b"),
            "antipode": format(antipode, "04b").replace("0", "a").replace("1", "b"),
            "element_abs": float(abs(element)),
            "element_real": float(element.real),
        })
    return rows


def flip_spectrum_facts() -> dict:
    """Spectrum of a single ideal all-flip term -J F on the monomer manifold."""
    flip = np.zeros((LOW_MANIFOLD_DIMENSION, LOW_MANIFOLD_DIMENSION), dtype=complex)
    flip[LOW_MANIFOLD_DIMENSION - 1, 0] = 1.0
    flip[0, LOW_MANIFOLD_DIMENSION - 1] = 1.0
    values = np.linalg.eigvalsh(-flip)
    return {
        "ground_energy": float(values[0]),
        "ground_degeneracy": int(np.sum(np.isclose(values, values[0], atol=1e-12))),
        "dark_state_count": int(np.sum(np.isclose(values, 0.0, atol=1e-12))),
        "statement": (
            "-J F has a unique ground state (|aaaa>+|bbbb|)/sqrt(2); the cat partner sits at +J and the 14 "
            "mixed monomers are dark at 0. A disjoint tiling of the generated term therefore has no code "
            "space at all (k=0), before any indistinguishability question arises."
        ),
    }


def ghz_readability() -> dict:
    """If a degenerate cat doublet span{|aaaa>,|bbbb>} were engineered anyway,
    a single-rung probe is already logical on it."""
    projector = np.zeros((LOW_MANIFOLD_DIMENSION, LOW_MANIFOLD_DIMENSION), dtype=complex)
    projector[0, 0] = 1.0
    projector[LOW_MANIFOLD_DIMENSION - 1, LOW_MANIFOLD_DIMENSION - 1] = 1.0
    report = {}
    for label in ("ZIII", "XIII", "YIII", "IZII"):
        probe = pauli_word(label)
        projected = projector @ probe @ projector
        scalar = np.trace(projected) / 2.0
        report[label] = float(np.linalg.norm(projected - scalar * projector, ord=2))
    return report


def main() -> None:
    rows = []
    for g in G_VALUES:
        candidate = MicroscopicCandidate2D(mott_u=U, maximum_sw_ratio=0.15, channels=crossed_channels(g))
        audit = evaluate_local_candidate(candidate, "XXXX", include_pauli_coefficients=True)
        coefficients = audit["full_traceless_pauli_coefficients"]
        effective = effective_from_coefficients(coefficients)
        antipodes = antipodal_elements(effective)
        all_flip = antipodes[0]
        mixed_max = max(row["element_abs"] for row in antipodes[1:])
        family = {label: coefficients[label] for label in FLIP_FAMILY}
        c_xxxx = family["XXXX"]
        sign_pattern_residual = max(
            abs(family[label] - FLIP_FAMILY_SIGNS[label] * c_xxxx) for label in FLIP_FAMILY
        )
        family_square = sum(value * value for value in family.values())
        fourbody_offdiag_square = sum(
            value * value for label, value in coefficients.items()
            if label != "IIII" and all(letter != "I" for letter in label) and any(letter in "XY" for letter in label)
        )
        rows.append({
            "g": g,
            "g_over_delta": g / DELTA,
            "all_flip_element": all_flip,
            "max_mixed_antipodal_element": mixed_max,
            "mixed_over_all_flip": float(mixed_max / all_flip["element_abs"]) if all_flip["element_abs"] > 0 else None,
            "offdiagonal_norm_by_flip_distance": flip_distance_split(effective),
            "flip_family_coefficients": family,
            "flip_family_sign_pattern_residual": sign_pattern_residual,
            "c_xxxx_over_all_flip_element": float(c_xxxx / all_flip["element_real"]) if all_flip["element_abs"] > 0 else None,
            "xxxx_share_within_flip_family": float(c_xxxx * c_xxxx / family_square) if family_square > 0 else None,
            "flip_family_share_of_fourbody_offdiagonal": float(family_square / fourbody_offdiag_square) if fourbody_offdiag_square > 0 else None,
            "reported_target_alignment": audit["state_vector"]["target_alignment"],
        })
    usable = [row for row in rows if row["all_flip_element"]["element_abs"] > 1e-14]
    x = np.log([row["g"] for row in usable])
    y = np.log([row["all_flip_element"]["element_abs"] for row in usable])
    power, intercept = np.polyfit(x, y, 1)
    out = {
        "schema": "antler.phase7c.quartet-monomial-projection.v1",
        "primitive": "crossed quartet d1(a0a1+b2b3), d2(b0b1+a2a3); U=20, Delta=10; no rail hops, no counterterms",
        "question": "full XXXX or a strict monomial subset?",
        "rows": rows,
        "all_flip_power_fit": {"power": float(power), "prefactor": float(np.exp(intercept))},
        "alignment_ceiling": {
            "statement": (
                "the off-diagonal effective operator equals c_F(|aaaa><bbbb|+h.c.) up to machine precision; "
                "its Pauli expansion fixes the squared XXXX alignment ceiling to 1/8 = 0.125, "
                "independent of couplings and of any diagonal counterterm"
            ),
            "squared_ceiling": 0.125,
        },
        "single_plaquette_flip_spectrum": flip_spectrum_facts(),
        "ghz_readability_of_engineered_cat_doublet": ghz_readability(),
        "claim_boundary": (
            "Correction-addendum control for Phase 7C. It verifies operator identity only. It promotes no candidate, "
            "no tiling, no code, no topological claim."
        ),
    }
    path = ROOT / "results" / "phase7" / "quartet_monomial_projection.json"
    path.write_text(json.dumps(out, indent=2), encoding="utf-8")
    print(json.dumps({
        "all_flip_power": out["all_flip_power_fit"],
        "g_0_5": {
            "all_flip": rows[1]["all_flip_element"]["element_real"],
            "max_mixed": rows[1]["max_mixed_antipodal_element"],
            "sign_residual": rows[1]["flip_family_sign_pattern_residual"],
            "xxxx_share_within_family": rows[1]["xxxx_share_within_flip_family"],
            "family_share_of_fourbody": rows[1]["flip_family_share_of_fourbody_offdiagonal"],
            "reported_alignment": rows[1]["reported_target_alignment"],
        },
        "flip_distance_norms_g_0_5": rows[1]["offdiagonal_norm_by_flip_distance"],
        "single_plaquette_spectrum": out["single_plaquette_flip_spectrum"],
        "ghz": out["ghz_readability_of_engineered_cat_doublet"],
    }, indent=2))


if __name__ == "__main__":
    main()
