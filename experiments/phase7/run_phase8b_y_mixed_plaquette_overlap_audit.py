"""Joint exact audit of a central-Y mixed check and an adjacent plaquette.

This is the next local geometry gate after the isolated Y-link audit.  The
mixed check YXZXII and the plaquette XZIIXZ share two links.  Their two
single-link anticommutations make the target checks commute.  Both are
generated by explicit neutral walkers and downfolded jointly, so this test
detects cross-walker Pauli words rather than assuming a stabilizer algebra.
"""
from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
from scipy import sparse
from scipy.sparse import linalg as sparse_linalg


ROOT = Path(__file__).resolve().parents[2]

DETUNING = 10.0
RATIOS = (0.20, 0.15, 0.10, 0.075, 0.05, 0.0375, 0.025)
EDGES = 6
GAUGE_DIMENSION = 1 << EDGES
MIXED_STATES = 4
PLAQUETTE_STATES = 4
DIMENSION = GAUGE_DIMENSION * MIXED_STATES * PLAQUETTE_STATES
PAULI_NAMES = "IXYZ"
MIXED_EDGES = (0, 1, 2, 3)
MIXED_PATTERN = (2, 1, 3, 1)  # Y X Z X
PLAQUETTE_EDGES = (0, 1, 4, 5)
PLAQUETTE_PATTERN = (1, 3, 1, 3)  # X Z X Z
MIXED_LABEL = "YXZXII"
PLAQUETTE_LABEL = "XZIIXZ"
# (YX)(XZ)ZX XZ = - ZY ZXXZ in the hermitian Pauli basis.
PRODUCT_LABEL = "ZYZXXZ"


def index(gauge: int, mixed_walker: int, plaquette_walker: int) -> int:
    return ((mixed_walker * PLAQUETTE_STATES + plaquette_walker) * GAUGE_DIMENSION) + gauge


def z_eigenvalue(gauge: int, edge: int) -> float:
    return -1.0 if (gauge >> edge) & 1 else 1.0


def add_symmetric(matrix: sparse.lil_matrix, row: int, column: int, value: complex) -> None:
    matrix[row, column] += value
    matrix[column, row] += np.conj(value)


def link_transition(gauge: int, edge: int, pauli: int, coupling: float) -> tuple[int, complex]:
    if pauli == 1:  # X
        return gauge ^ (1 << edge), coupling
    if pauli == 2:  # i X Z = Y
        return gauge ^ (1 << edge), 1j * coupling * z_eigenvalue(gauge, edge)
    if pauli == 3:  # Z
        return gauge, coupling * z_eigenvalue(gauge, edge)
    raise ValueError(f"unsupported Pauli code {pauli}")


def add_walker_transitions(
    matrix: sparse.lil_matrix,
    gauge: int,
    mixed_walker: int,
    plaquette_walker: int,
    coupling: float,
    *,
    which: str,
) -> None:
    if which == "mixed":
        states, edges, pattern, walker = MIXED_STATES, MIXED_EDGES, MIXED_PATTERN, mixed_walker
    else:
        states, edges, pattern, walker = PLAQUETTE_STATES, PLAQUETTE_EDGES, PLAQUETTE_PATTERN, plaquette_walker
    next_walker = (walker + 1) % states
    next_gauge, amplitude = link_transition(gauge, edges[walker], pattern[walker], coupling)
    if which == "mixed":
        row = index(next_gauge, next_walker, plaquette_walker)
    else:
        row = index(next_gauge, mixed_walker, next_walker)
    add_symmetric(matrix, row, index(gauge, mixed_walker, plaquette_walker), amplitude)


def build_hamiltonian(coupling: float) -> sparse.csr_matrix:
    hamiltonian = sparse.lil_matrix((DIMENSION, DIMENSION), dtype=complex)
    for gauge in range(GAUGE_DIMENSION):
        for mixed_walker in range(MIXED_STATES):
            for plaquette_walker in range(PLAQUETTE_STATES):
                column = index(gauge, mixed_walker, plaquette_walker)
                if mixed_walker:
                    hamiltonian[column, column] += DETUNING
                if plaquette_walker:
                    hamiltonian[column, column] += DETUNING
                add_walker_transitions(
                    hamiltonian, gauge, mixed_walker, plaquette_walker, coupling, which="mixed"
                )
                add_walker_transitions(
                    hamiltonian, gauge, mixed_walker, plaquette_walker, coupling, which="plaquette"
                )
    return hamiltonian.tocsr()


def pauli_action(codes: tuple[int, ...], state: int) -> tuple[int, complex]:
    target = state
    phase = 1.0 + 0.0j
    for edge, code in enumerate(codes):
        bit = (state >> edge) & 1
        if code == 1:
            target ^= 1 << edge
        elif code == 2:
            target ^= 1 << edge
            phase *= 1j if bit == 0 else -1j
        elif code == 3:
            phase *= -1.0 if bit else 1.0
    return target, phase


def pauli_coefficients(hamiltonian: np.ndarray) -> dict[str, complex]:
    coefficients: dict[str, complex] = {}
    for codes in itertools.product(range(4), repeat=EDGES):
        value = 0.0j
        for column in range(GAUGE_DIMENSION):
            row, phase = pauli_action(codes, column)
            value += np.conj(phase) * hamiltonian[row, column]
        coefficients["".join(PAULI_NAMES[code] for code in codes)] = value / GAUGE_DIMENSION
    return coefficients


def pauli_matrix(codes: tuple[int, ...]) -> np.ndarray:
    matrix = np.zeros((GAUGE_DIMENSION, GAUGE_DIMENSION), dtype=complex)
    for column in range(GAUGE_DIMENSION):
        row, phase = pauli_action(codes, column)
        matrix[row, column] = phase
    return matrix


def downfold_at_zero(hamiltonian: sparse.csr_matrix) -> tuple[np.ndarray, float]:
    low = np.asarray([index(gauge, 0, 0) for gauge in range(GAUGE_DIMENSION)], dtype=int)
    mask = np.ones(DIMENSION, dtype=bool)
    mask[low] = False
    high = np.flatnonzero(mask)
    h_lh = hamiltonian[low][:, high]
    h_hh = hamiltonian[high][:, high].tocsc()
    h_hl = hamiltonian[high][:, low].toarray()
    effective = -np.asarray(h_lh @ sparse_linalg.spsolve(h_hh, h_hl))
    return effective, float(np.linalg.norm(effective - effective.conj().T, ord="fro"))


def main() -> None:
    mixed = pauli_matrix((2, 1, 3, 1, 0, 0))
    plaquette = pauli_matrix((1, 3, 0, 0, 1, 3))
    rows = []
    for ratio in RATIOS:
        effective, hermiticity = downfold_at_zero(build_hamiltonian(ratio * DETUNING))
        coefficients = pauli_coefficients(effective)
        allowed = {"IIIIII", MIXED_LABEL, PLAQUETTE_LABEL, PRODUCT_LABEL}
        unwanted = {label: value for label, value in coefficients.items() if label not in allowed}
        label, value = max(unwanted.items(), key=lambda item: abs(item[1]))
        rows.append({
            "coupling_over_detuning": ratio,
            "mixed_yxzx_coefficient": float(np.real_if_close(coefficients[MIXED_LABEL])),
            "plaquette_xz_iixz_coefficient": float(np.real_if_close(coefficients[PLAQUETTE_LABEL])),
            "commuting_product_coefficient": float(np.real_if_close(coefficients[PRODUCT_LABEL])),
            "maximum_outside_generated_algebra_coefficient": float(abs(value)),
            "largest_outside_generated_algebra_pauli": label,
            "zero_energy_schur_hermiticity_residual": hermiticity,
            "target_commutator_frobenius": float(np.linalg.norm(mixed @ plaquette - plaquette @ mixed, ord="fro")),
        })
    deep = [row for row in rows if row["coupling_over_detuning"] <= 0.075]
    powers = {
        name: float(np.polyfit(
            np.log([row["coupling_over_detuning"] for row in deep]),
            np.log(np.abs([row[name] for row in deep])),
            1,
        )[0])
        for name in ("mixed_yxzx_coefficient", "plaquette_xz_iixz_coefficient", "commuting_product_coefficient")
    }
    output = {
        "schema": "antler.phase8b.y-mixed-plaquette-overlap-audit.v1",
        "parameters": {
            "gauge_links": EDGES,
            "detuning": DETUNING,
            "ratios": list(RATIOS),
            "mixed_check": MIXED_LABEL,
            "plaquette": PLAQUETTE_LABEL,
            "shared_links": [0, 1],
            "y_link_realization": "forward hop i*g*Z followed by gauge-bit flip",
            "new_primitives": "two neutral four-state phase-controlled X/Y/Z-conditioned walkers",
            "downfolding": "exact zero-energy Schur complement onto both walkers low",
        },
        "dimensions": {"total": DIMENSION, "low_gauge_subspace": GAUGE_DIMENSION, "high_walker_subspace": DIMENSION - GAUGE_DIMENSION},
        "rows": rows,
        "deep_sw_powers": powers,
        "decision": (
            "The explicit central-Y mixed check and its adjacent plaquette jointly close on their commuting local algebra. "
            "No Pauli word outside {I,mixed,plaquette,product} is resolved in the overlap block."
        ),
        "claim_boundary": (
            "This is a local mixed-check compatibility audit, not a complete published twist/dislocation geometry. It does not "
            "establish a branch cut, fusion-space dimension, local indistinguishability, defect motion, a non-Abelian braid, "
            "a native ANTLER realization or fault tolerance."
        ),
    }
    result = ROOT / "results" / "phase7" / "phase8b_y_mixed_plaquette_overlap_audit.json"
    result.write_text(json.dumps(output, indent=2), encoding="utf-8")
    print(json.dumps(output, indent=2))


if __name__ == "__main__":
    main()
